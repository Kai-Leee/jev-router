import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {mkdir,writeFile} from 'node:fs/promises';
import {resolve,join} from 'node:path';

// Uses an existing Playwright package/browser; never installs or invokes models.
const packagePath=process.env.JEV_PLAYWRIGHT_PACKAGE;
const executablePath=process.env.JEV_CHROME_EXECUTABLE;
const url=process.argv[2];
if(!packagePath||!executablePath||!url)throw new Error('Set JEV_PLAYWRIGHT_PACKAGE and JEV_CHROME_EXECUTABLE; pass a synthetic dashboard URL.');
const target=new URL(url);
if(!['127.0.0.1','localhost'].includes(target.hostname))throw new Error('Loopback URL required.');
const {chromium}=createRequire(resolve(packagePath))('playwright');
const output=resolve('output/playwright');await mkdir(output,{recursive:true});
const browser=await chromium.launch({executablePath,headless:true});
const checks=[],pageErrors=[];let snapshotRequests=0;
const page=await browser.newPage({viewport:{width:1440,height:1000}});
page.on('pageerror',error=>pageErrors.push(error.message));
page.on('request',request=>{if(request.url().endsWith('/api/snapshot'))snapshotRequests++;});
const record=name=>checks.push({name,status:'passed'});
const snapshot=async name=>writeFile(join(output,`${name}.txt`),await page.locator('body').ariaSnapshot());
const selected=()=>page.locator('.run-option[aria-current="true"]').getAttribute('data-run-id');
try {
  await page.goto(url);await page.locator('#selected-run').waitFor({state:'visible'});
  await snapshot('initial-snapshot');
  assert.equal(await page.locator('.run-option').count(),3);
  await page.locator('[data-run-id="r0-synthetic-completed"]').click();
  assert.match(await page.locator('#evidence-banner').innerText(),/합성 테스트/);
  assert.match(await page.locator('#headline-metrics').innerText(),/2회/);
  const totals=await page.locator('.provider-total').allTextContents();
  assert.match(totals[0],/205/);assert.match(totals[1],/420/);
  assert.match(await page.locator('#cost-providers').innerText(),/\$0\.1234/);
  assert.match(await page.locator('#cost-providers').innerText(),/실제 청구 USD\s*미확인/);
  record('synthetic calls, tokens, estimated cost and unknown billed amount');
  await page.screenshot({path:join(output,'dashboard-desktop.png'),fullPage:true});
  await page.locator('#run-search').fill('uncertain');
  assert.equal(await page.locator('.run-option').count(),1);
  assert.equal(await selected(),'r0-synthetic-uncertain');
  assert.match(await page.locator('#run-status').innerText(),/불확실/);
  assert.match(await page.locator('#token-providers').innerText(),/미확인/);
  record('search and uncertain run keep unknown usage');
  await page.locator('#run-search').fill('');
  await page.locator('#kind-filter').selectOption('live');
  assert.equal(await page.locator('.run-option').count(),0);
  assert.equal(await page.locator('#selected-run').isHidden(),true);
  assert.match(await page.locator('#empty-title').innerText(),/조건에 맞는/);
  record('evidence-kind filter empty state');
  await page.locator('#kind-filter').selectOption('synthetic');
  await page.locator('[data-run-id="r0-synthetic-prepared"]').click();
  assert.match(await page.locator('#headline-metrics').innerText(),/미확인/);
  record('prepared run does not invent zero usage');
  await page.locator('[data-run-id="r0-synthetic-completed"]').click();
  await page.locator('#refresh-button').click();
  await page.waitForFunction(()=>!document.getElementById('refresh-button').disabled);
  assert.equal(await selected(),'r0-synthetic-completed');
  assert.match(await page.locator('#refresh-announcement').innerText(),/새로고침했습니다/);
  record('manual refresh preserves selected run');
  const before=snapshotRequests;
  await page.waitForResponse(response=>response.url().endsWith('/api/snapshot')&&response.ok(),{timeout:6000});
  assert.ok(snapshotRequests>before);assert.equal(await selected(),'r0-synthetic-completed');
  record('automatic refresh without navigation');
  await page.route('**/api/snapshot',route=>route.fulfill({status:503,body:'unavailable'}));
  await page.locator('#refresh-button').click();
  await page.locator('#api-error').waitFor({state:'visible'});
  assert.match(await page.locator('#api-error').innerText(),/마지막으로 받은 기록/);
  assert.match((await page.locator('.provider-total').allTextContents())[1],/420/);
  record('snapshot failure keeps last known data with warning');
  await page.unroute('**/api/snapshot');
  await page.locator('#refresh-button').click();
  await page.locator('#api-error').waitFor({state:'hidden'});
  record('snapshot recovery clears stale warning');
  await page.setViewportSize({width:390,height:844});
  await snapshot('mobile-snapshot');
  const size=await page.evaluate(()=>({scroll:document.documentElement.scrollWidth,viewport:innerWidth}));
  assert.ok(size.scroll<=size.viewport,`horizontal overflow ${size.scroll}/${size.viewport}`);
  await page.screenshot({path:join(output,'dashboard-mobile.png'),fullPage:true});
  record('390px mobile viewport without page overflow');
  assert.deepEqual(pageErrors,[]);record('no browser page errors');
  const report={status:'passed',evidence_kind:'synthetic',model_inference:false,checks,page_errors:pageErrors};
  await writeFile(join(output,'browser-check.json'),JSON.stringify(report,null,2)+'\n');
  console.log(JSON.stringify(report,null,2));
} catch(error) {
  await writeFile(join(output,'browser-check.json'),JSON.stringify({status:'failed',checks,error:error.message,page_errors:pageErrors},null,2)+'\n');
  throw error;
} finally {await browser.close();}
